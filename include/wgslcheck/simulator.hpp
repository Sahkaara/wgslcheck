#pragma once

#include <array>
#include <string>
#include <vector>

#include "wgslcheck/ast.hpp"
#include "wgslcheck/diagnostic.hpp"

namespace wgslcheck {

/**
 * @brief Configuration options for the CPU-side simulation.
 */
struct SimulationOptions {
    /**
     * @brief The dispatch grid size (number of workgroups in X, Y, Z).
     * Defaults to a single workgroup (1, 1, 1).
     */
    std::array<unsigned, 3> workgroups{1, 1, 1};
    
    /**
     * @brief The name of the function to execute (e.g., "main").
     * If empty, the simulator will attempt to auto-detect a compute entry point.
     */
    std::string entry_point;
    
    /**
     * @brief A safety mechanism to prevent infinite loops or runaway CPU usage.
     * 
     * Since we are interpreting WGSL on the CPU, an unbounded loop could freeze
     * the host application. The simulator will abort with a diagnostic error 
     * if this limit is exceeded.
     */
    std::size_t max_invocations = 4096;
};

/**
 * @brief Aggregates the results of a simulation run.
 */
struct SimulationResult {
    /**
     * @brief Captures the output generated by the shader (e.g., `debugPrint`).
     * Each line of output is stored as a separate string.
     */
    std::vector<std::string> output;
    
    /**
     * @brief Any runtime errors encountered during execution 
     * (e.g., out-of-bounds access, exceeding `max_invocations`).
     */
    std::vector<Diagnostic> diagnostics;

    /**
     * @brief Checks if the simulation completed successfully without errors.
     */
    bool ok() const noexcept { return !has_errors(diagnostics); }
};

/**
 * @brief The Simulator executes WGSL compute shaders directly on the CPU.
 * 
 * This allows developers to test kernel logic, math, and control flow without 
 * requiring a GPU or a browser environment. It interprets the AST line by line.
 */
class Simulator {
public:
    /**
     * @brief Executes the compute shader AST.
     * 
     * @param module The parsed AST to execute.
     * @param options Configuration for the entry point and dispatch size.
     * @return A `SimulationResult` containing the output and runtime diagnostics.
     * 
     * @note Marked `const` because interpreting the AST shouldn't modify the 
     * underlying tree structure.
     */
    SimulationResult run(const Module& module, const SimulationOptions& options) const;
};

} // namespace wgslcheck